def __getattr__(name: str) -> Any:
    if name in ("score_g4", "score_g4_from_files"):
        from w07_g4_scorer import scorer

        return getattr(scorer, name)
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


